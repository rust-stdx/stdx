//! The thread-local, periodically re-seeded generator.

use core::cell::RefCell;
use std::thread_local;

use crate::{
    rng::{Rng, SeedableRng, TryRng},
    rngs::{ChaChaRng, SystemRng},
};

/// Number of bytes produced by the thread-local generator before it is
/// re-seeded from the operating system.
pub(crate) const RESEED_INTERVAL: usize = 64 * 1024;

/// A [`ChaChaRng`] that re-seeds itself from a fallible entropy source.
///
/// Every seed is 40 bytes: a fresh 32-byte key and a fresh 8-byte nonce.
pub(crate) struct Reseeding<S> {
    rng: ChaChaRng,
    source: S,
    remaining: usize,
}

impl<S: TryRng> Reseeding<S> {
    /// Creates a generator seeded from `source`.
    pub(crate) fn new(mut source: S) -> Result<Self, S::Error> {
        let mut seed = [0u8; 40];
        source.try_fill_bytes(&mut seed)?;
        Ok(Self {
            rng: ChaChaRng::from_seed(seed),
            source,
            remaining: RESEED_INTERVAL,
        })
    }

    /// Replaces the generator state with a fresh seed from the source.
    fn reseed(&mut self) -> Result<(), S::Error> {
        let mut seed = [0u8; 40];
        self.source.try_fill_bytes(&mut seed)?;
        self.rng = ChaChaRng::from_seed(seed);
        self.remaining = RESEED_INTERVAL;
        Ok(())
    }

    /// Fills `dst`, re-seeding exactly at [`RESEED_INTERVAL`] boundaries.
    pub(crate) fn try_fill_bytes(&mut self, dst: &mut [u8]) -> Result<(), S::Error> {
        let mut written = 0;
        while written < dst.len() {
            if self.remaining == 0 {
                self.reseed()?;
            }
            let take = core::cmp::min(self.remaining, dst.len() - written);
            self.rng.fill_bytes(&mut dst[written..written + take]);
            self.remaining -= take;
            written += take;
        }
        Ok(())
    }

    /// Fills `dst`, panicking if the entropy source fails.
    fn fill_bytes(&mut self, dst: &mut [u8]) {
        self.try_fill_bytes(dst)
            .unwrap_or_else(|_| panic!("failed to obtain entropy from the operating system"));
    }

    fn next_u32(&mut self) -> u32 {
        let mut bytes = [0u8; 4];
        self.fill_bytes(&mut bytes);
        u32::from_le_bytes(bytes)
    }

    fn next_u64(&mut self) -> u64 {
        let mut bytes = [0u8; 8];
        self.fill_bytes(&mut bytes);
        u64::from_le_bytes(bytes)
    }
}

thread_local! {
    static THREAD_RNG: RefCell<Reseeding<SystemRng>> = RefCell::new(
        Reseeding::new(SystemRng)
            .unwrap_or_else(|_| panic!("failed to obtain entropy from the operating system"))
    );
}

/// Returns a handle to the current thread's random number generator.
///
/// The generator is a ChaCha12 stream that is re-seeded from
/// [`SystemRng`](crate::SystemRng) after every 64 KiB of output. This makes it
/// fast while retaining forward secrecy: compromising the generator state does
/// not reveal previously generated bytes.
///
/// Each thread has its own generator, seeded independently. The returned value
/// is a cheap, zero-sized handle; obtaining it repeatedly is free.
///
/// # Panics
///
/// The first call on a thread panics if the operating system cannot provide
/// entropy. Use [`SystemRng`](crate::SystemRng) directly if you need to handle
/// that failure.
pub fn thread_rng() -> impl Rng {
    ThreadRng
}

struct ThreadRng;

impl Rng for ThreadRng {
    fn next_u32(&mut self) -> u32 {
        THREAD_RNG.with(|cell| cell.borrow_mut().next_u32())
    }

    fn next_u64(&mut self) -> u64 {
        THREAD_RNG.with(|cell| cell.borrow_mut().next_u64())
    }

    fn fill_bytes(&mut self, dst: &mut [u8]) {
        THREAD_RNG.with(|cell| cell.borrow_mut().fill_bytes(dst))
    }
}

#[cfg(test)]
mod tests {
    use core::cell::Cell;
    use std::{rc::Rc, vec};

    use super::*;

    /// A source that returns the same byte for every byte of a seed, advancing
    /// the byte for each call, and records how often it was used.
    #[derive(Clone)]
    struct MockSource {
        next: Rc<Cell<u8>>,
        calls: Rc<Cell<usize>>,
    }

    impl MockSource {
        fn new() -> (Self, Rc<Cell<u8>>, Rc<Cell<usize>>) {
            let next = Rc::new(Cell::new(0));
            let calls = Rc::new(Cell::new(0));
            (
                Self {
                    next: Rc::clone(&next),
                    calls: Rc::clone(&calls),
                },
                next,
                calls,
            )
        }
    }

    impl TryRng for MockSource {
        type Error = core::convert::Infallible;

        fn try_next_u32(&mut self) -> Result<u32, Self::Error> {
            Ok(0)
        }

        fn try_fill_bytes(&mut self, dst: &mut [u8]) -> Result<(), Self::Error> {
            dst.fill(self.next.get());
            self.next.set(self.next.get().wrapping_add(1));
            self.calls.set(self.calls.get() + 1);
            Ok(())
        }
    }

    #[test]
    fn reseeds_exactly_at_the_interval_boundary() {
        let (source, _next, calls) = MockSource::new();
        let mut rng = Reseeding::new(source).unwrap();
        assert_eq!(calls.get(), 1, "the initial seed consumes one call");

        let mut bytes = vec![0u8; RESEED_INTERVAL - 1];
        rng.fill_bytes(&mut bytes);
        assert_eq!(calls.get(), 1, "no re-seed before the boundary");

        rng.fill_bytes(&mut bytes[..1]);
        assert_eq!(calls.get(), 1, "the last byte of the interval uses the old seed");

        rng.fill_bytes(&mut bytes[..1]);
        assert_eq!(calls.get(), 2, "the next byte triggers a re-seed");
    }

    #[test]
    fn output_after_reseed_matches_a_fresh_seed() {
        let (source, _next, _calls) = MockSource::new();
        let mut rng = Reseeding::new(source).unwrap();

        let mut skip = vec![0u8; RESEED_INTERVAL];
        rng.fill_bytes(&mut skip);

        // The mock source returned seed 0 for the initial state and seed 1 for
        // the re-seed.
        let mut expected = ChaChaRng::from_seed([1u8; 40]);
        let mut expected_bytes = [0u8; 257];
        expected.fill_bytes(&mut expected_bytes);

        let mut actual = [0u8; 257];
        rng.fill_bytes(&mut actual);
        assert_eq!(actual, expected_bytes);
    }

    #[test]
    fn a_single_large_fill_crosses_many_intervals() {
        let (source, _next, calls) = MockSource::new();
        let mut rng = Reseeding::new(source).unwrap();

        let mut bytes = vec![0u8; RESEED_INTERVAL * 3 + 17];
        rng.fill_bytes(&mut bytes);
        // One initial seed plus one re-seed per full interval consumed.
        assert_eq!(calls.get(), 4);
    }

    #[test]
    fn zero_length_fill_does_not_reseed() {
        let (source, _next, calls) = MockSource::new();
        let mut rng = Reseeding::new(source).unwrap();
        rng.fill_bytes(&mut []);
        assert_eq!(calls.get(), 1);
    }

    #[test]
    fn source_errors_are_propagated_by_try_fill_bytes() {
        struct FailingSource {
            fail: bool,
        }

        impl TryRng for FailingSource {
            type Error = ();

            fn try_next_u32(&mut self) -> Result<u32, Self::Error> {
                Err(())
            }

            fn try_fill_bytes(&mut self, dst: &mut [u8]) -> Result<(), Self::Error> {
                if self.fail {
                    Err(())
                } else {
                    dst.fill(7);
                    Ok(())
                }
            }
        }

        assert!(
            Reseeding::new(FailingSource {
                fail: true
            })
            .is_err()
        );

        let mut rng = Reseeding::new(FailingSource {
            fail: false,
        })
        .unwrap();
        let mut buffer = vec![0u8; RESEED_INTERVAL];
        rng.try_fill_bytes(&mut buffer).unwrap();

        // Force a re-seed that will fail.
        rng.source.fail = true;
        assert!(rng.try_fill_bytes(&mut buffer[..1]).is_err());
    }

    #[test]
    fn thread_rng_produces_different_values() {
        let mut rng = thread_rng();
        let mut first = [0u8; 32];
        let mut second = [0u8; 32];
        rng.fill_bytes(&mut first);
        rng.fill_bytes(&mut second);
        assert_ne!(first, second);
    }

    #[test]
    fn thread_rng_works_in_spawned_threads() {
        let first = std::thread::spawn(|| {
            let mut rng = thread_rng();
            let mut bytes = [0u8; 32];
            rng.fill_bytes(&mut bytes);
            bytes
        })
        .join()
        .unwrap();

        let second = std::thread::spawn(|| {
            let mut rng = thread_rng();
            let mut bytes = [0u8; 32];
            rng.fill_bytes(&mut bytes);
            bytes
        })
        .join()
        .unwrap();

        assert_ne!(first, second);
    }

    #[test]
    fn thread_rng_survives_a_reseed_boundary() {
        let mut rng = thread_rng();
        let mut bytes = vec![0u8; RESEED_INTERVAL + 1];
        rng.fill_bytes(&mut bytes);
        assert!(bytes.iter().any(|&byte| byte != 0));
    }
}
