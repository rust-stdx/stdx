/// The target dispatches `p1600` to a hardware kernel; it must agree with the
/// independent reference for every supported round count and many random
/// states.
#[test]
fn p1600_dispatched_matches_reference_all_rounds() {
    let mut rng = ChaChaRng::seed_from_u64(0x0123_4567_89ab_cdef);

    macro_rules! check {
        ($($rounds:literal),* $(,)?) => {
            $({
                for case in 0..64 {
                    let mut actual = rng.random::<[u64; 25]>();
                    let mut expected = actual;
                    p1600::<$rounds>(&mut actual);
                    keccak_p::<$rounds>(&mut expected);
                    assert_eq!(actual, expected, "ROUNDS={}, case={case}", $rounds);
                }
            })*
        };
    }

    check!(1, 2, 3, 4, 5, 6, 7, 8, 11, 12, 13, 16, 17, 23, 24);

    // Degenerate states: all-zero and all-ones.
    macro_rules! check_fill {
        ($($rounds:literal),* $(,)?) => {
            $({
                for fill in [0u64, u64::MAX] {
                    let mut actual = [fill; 25];
                    let mut expected = actual;
                    p1600::<$rounds>(&mut actual);
                    keccak_p::<$rounds>(&mut expected);
                    assert_eq!(actual, expected, "ROUNDS={} fill={fill:#x}", $rounds);
                }
            })*
        };
    }
    check_fill!(1, 2, 12, 16, 24);
}

/// States whose bytes are the serialized sponge state (the values the
/// `transmute` in `permute_state_bytes` exposes) must permute identically after
/// a little-endian byte round-trip.
#[test]
fn p1600_matches_reference_for_serialized_byte_states() {
    let mut rng = ChaChaRng::seed_from_u64(0xdead_beef_1234_5678);
    for _ in 0..32 {
        let mut lanes = rng.random::<[u64; 25]>();
        let mut bytes = [0u8; 200];
        for (i, lane) in lanes.iter().enumerate() {
            bytes[8 * i..8 * i + 8].copy_from_slice(&lane.to_le_bytes());
        }
        let mut from_bytes = [0u64; 25];
        for (i, lane) in from_bytes.iter_mut().enumerate() {
            *lane = u64::from_le_bytes(bytes[8 * i..8 * i + 8].try_into().unwrap());
        }
        assert_eq!(from_bytes, lanes);

        p1600::<24>(&mut lanes);
        keccak_p::<24>(&mut from_bytes);
        assert_eq!(lanes, from_bytes);
    }
}

/// Reports which backend the target actually executed and cross-checks the name
/// against runtime feature detection, so a silent fallback to scalar in a
/// "passing" run is visible in the report.
#[test]
fn backend_detection_is_consistent_with_the_cpu() {
    let name = keccak_backend_name();
    assert!(
        matches!(name, "scalar" | "avx2" | "avx512" | "armv8.4-sha3"),
        "unexpected backend name {name}"
    );

    #[cfg(all(target_arch = "aarch64", feature = "std"))]
    {
        let detected = std::arch::is_aarch64_feature_detected!("sha3");
        assert_eq!(
            name,
            if detected { "armv8.4-sha3" } else { "scalar" },
            "the single-state backend must follow FEAT_SHA3 detection"
        );
    }

    #[cfg(all(target_arch = "x86_64", feature = "std"))]
    {
        let has_avx512 = std::arch::is_x86_feature_detected!("avx512f");
        assert_eq!(has_avx512, name == "avx512", "avx512f must select the AVX-512 kernel");
        if name == "avx2" {
            assert!(std::arch::is_x86_feature_detected!("avx2"));
        }
    }

    #[cfg(all(target_arch = "wasm32", target_feature = "simd128"))]
    assert!(matches!(name, "scalar" | "wasm-simd128"));

    let batch_name = parallel_hash_backend_name();
    assert!(
        matches!(
            batch_name,
            "scalar" | "neon" | "avx2" | "avx512" | "armv8.4-sha3" | "wasm-simd128"
        ),
        "unexpected batched backend name {batch_name}"
    );
    #[cfg(all(target_arch = "aarch64", feature = "std"))]
    assert_eq!(
        batch_name,
        if std::arch::is_aarch64_feature_detected!("sha3") {
            "armv8.4-sha3"
        } else {
            "neon"
        }
    );
    #[cfg(all(target_arch = "wasm32", target_feature = "simd128"))]
    assert_eq!(batch_name, "wasm-simd128");
}

