/// All 199 admissible rates, eight delimiters (including 0, 0x80 and values
/// whose low bit collides with the 0x80 padding bit), and message lengths at
/// every rate boundary.
#[test]
fn sponge_all_rates_delimiters_and_boundaries() {
    let delimiters = [0x00u8, 0x01, 0x04, 0x06, 0x07, 0x1f, 0x80, 0xff];

    for rate in 1..200usize {
        let lengths = [
            0usize,
            1,
            rate.saturating_sub(2),
            rate - 1,
            rate,
            rate + 1,
            2 * rate - 1,
            2 * rate,
            2 * rate + 1,
        ];
        let out_len = 2 * rate + 7;

        for &delimiter in &delimiters {
            for &len in &lengths {
                let data = pattern(len, rate as u8);
                let expected = ref_sponge::<24>(&data, rate, delimiter, out_len);

                let mut sponge = KeccakSponge::<24>::new(rate, delimiter);
                sponge.absorb(&data);
                let mut actual = vec![0u8; out_len];
                sponge.squeeze(&mut actual);
                assert_eq!(actual, expected, "one-shot rate={rate} delimiter={delimiter:#04x} len={len}");
            }
        }
    }
}

/// Chunked absorb and squeeze must be independent of the chunking, including
/// chunk sizes that straddle `rate` and the 8-byte word boundary.
#[test]
fn sponge_chunked_absorb_and_squeeze_across_rates() {
    let rates = [1usize, 2, 3, 7, 8, 9, 71, 72, 73, 135, 136, 137, 167, 168, 169, 199];
    let delimiters = [0x06u8, 0x1f];
    let chunks = [1usize, 2, 3, 7, 8, 9, 63, 64, 65];

    for &rate in &rates {
        let lengths = [0usize, 1, rate - 1, rate, rate + 1, 2 * rate + 5];
        for &delimiter in &delimiters {
            for &len in &lengths {
                let data = pattern(len, 0x5a);
                let out_len = 2 * rate + 9;
                let expected = ref_sponge::<24>(&data, rate, delimiter, out_len);

                for &chunk in &chunks {
                    let mut sponge = KeccakSponge::<24>::new(rate, delimiter);
                    for part in data.chunks(chunk) {
                        sponge.absorb(part);
                    }
                    let mut actual = vec![0u8; out_len];
                    let mut offset = 0;
                    let mut index = 0;
                    while offset < actual.len() {
                        let take = core::cmp::min(chunks[index % chunks.len()], actual.len() - offset);
                        sponge.squeeze(&mut actual[offset..offset + take]);
                        offset += take;
                        index += 1;
                    }
                    assert_eq!(
                        actual, expected,
                        "rate={rate} delimiter={delimiter:#04x} len={len} chunk={chunk}"
                    );
                }
            }
        }
    }
}

/// A zero-length squeeze must not lose or duplicate output bytes.
#[test]
fn sponge_zero_length_squeezes_are_transparent() {
    let data = pattern(400, 3);
    for rate in [1usize, 8, 136, 199] {
        let expected = ref_sponge::<24>(&data, rate, 0x1f, 3 * rate + 1);
        let mut sponge = KeccakSponge::<24>::new(rate, 0x1f);
        sponge.absorb(&data);
        sponge.squeeze(&mut []);
        let mut actual = vec![0u8; expected.len()];
        let mut offset = 0;
        while offset < actual.len() {
            let take = core::cmp::min(1 + offset % 7, actual.len() - offset);
            sponge.squeeze(&mut actual[offset..offset + take]);
            offset += take;
            sponge.squeeze(&mut []);
        }
        assert_eq!(actual, expected, "rate={rate}");
    }
}

/// The output buffer is written exactly `out.len()` bytes, at a non-zero offset
/// inside a larger allocation, and the canaries around it are untouched.
#[test]
fn sponge_output_respects_slice_bounds_and_canaries() {
    let data = pattern(1000, 9);
    for rate in [8usize, 72, 136, 168] {
        for &len in &[0usize, 1, 7, 8, rate - 1, rate, rate + 1, 2 * rate + 3] {
            let expected = ref_sponge::<24>(&data, rate, 0x1f, len);

            let mut buffer = vec![0xAAu8; len + 32];
            let mut sponge = KeccakSponge::<24>::new(rate, 0x1f);
            sponge.absorb(&data);
            sponge.squeeze(&mut buffer[16..16 + len]);
            assert_eq!(&buffer[16..16 + len], &expected[..], "rate={rate} len={len}");
            assert!(buffer[..16].iter().all(|&b| b == 0xAA), "front canary rate={rate} len={len}");
            assert!(
                buffer[16 + len..].iter().all(|&b| b == 0xAA),
                "back canary rate={rate} len={len}"
            );
        }
    }
}

