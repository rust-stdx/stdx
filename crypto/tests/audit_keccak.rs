/// Sweep block sizes and message lengths around every batching boundary and
/// compare with the SP 800-185 reference. This is the test that catches
/// off-by-one block splitting errors in `update` and the batched leaf path.
#[test]
fn parallel_hash_matches_reference_across_block_sizes() {
    let settings: &[(usize, &[u8])] = &[
        (1, b""),
        (2, b""),
        (3, b""),
        (7, b""),
        (8, b""),
        (9, b"Parallel Data"),
        (12, b""),
        (16, b"x"),
        (63, b""),
        (64, b""),
        (65, b""),
        (117, b""),
        (135, b""),
        (136, b""),
        (137, b""),
        (168, b""),
    ];

    let mut rng = ChaChaRng::seed_from_u64(0xfeed_face_cafe_beef);
    for &(block_size, customization) in settings {
        let lengths = [
            0usize,
            1,
            block_size.saturating_sub(1),
            block_size,
            block_size + 1,
            2 * block_size,
            2 * block_size + 1,
            3 * block_size,
            3 * block_size + 5,
        ];
        for &len in &lengths {
            let data = {
                let mut v = vec![0u8; len];
                rng.fill(&mut v);
                v
            };
            let expected = ref_parallel_hash(&data, block_size, customization, 64, false);

            let mut out = [0u8; 64];
            ParallelHash256::hash(&data, block_size, customization, &mut out).unwrap();
            assert_eq!(out[..], expected[..], "B={block_size} len={len} custom={}", customization.len());
        }
    }
}

/// Feeding the same bytes in arbitrary chunks must not change the digest. This
/// exercises the queue/partial-block logic and the "short final batch" lane
/// aliasing in `update`.
#[test]
fn parallel_hash_streaming_is_chunk_independent() {
    let settings = [(1usize, 24usize), (2, 5), (8, 40), (12, 37), (136, 300), (137, 300)];

    for (block_size, len) in settings {
        let data = pattern(len, block_size as u8);

        let mut one_shot = [0u8; 64];
        ParallelHash256::hash(&data, block_size, b"stream", &mut one_shot).unwrap();
        assert_eq!(
            one_shot[..],
            ref_parallel_hash(&data, block_size, b"stream", 64, false)[..],
            "one-shot B={block_size} len={len}"
        );

        for chunk in [1usize, 2, 3, 5, 7, 8, 9, block_size / 2 + 1, block_size, block_size + 1] {
            let mut hasher = ParallelHash256::new(block_size, b"stream").unwrap();
            for part in data.chunks(chunk) {
                hasher.update(part);
            }
            let mut streamed = [0u8; 64];
            hasher.finalize_into(&mut streamed);
            assert_eq!(streamed[..], one_shot[..], "B={block_size} len={len} chunk={chunk}");
        }
    }
}

/// The XOF form binds `L = 0`; chunked reads must be prefix-consistent and must
/// match the reference.
#[test]
fn parallel_hash_xof_matches_reference_and_chunking() {
    for (block_size, len) in [(1usize, 3usize), (8, 24), (16, 40), (136, 300), (1024, 5000)] {
        let data = pattern(len, 0x21);
        let expected = ref_parallel_hash(&data, block_size, b"xof", 517, true);

        let mut hasher = ParallelHash256::new(block_size, b"xof").unwrap();
        hasher.update(&data);
        let mut reader = hasher.finalize_xof();
        let mut actual = vec![0u8; expected.len()];
        let mut offset = 0;
        let mut index = 0;
        let sizes = [1usize, 7, 8, 63, 64, 65, 136, 137];
        while offset < actual.len() {
            let take = core::cmp::min(sizes[index % sizes.len()], actual.len() - offset);
            reader.squeeze(&mut actual[offset..offset + take]);
            offset += take;
            index += 1;
        }
        assert_eq!(actual, expected, "B={block_size} len={len}");
    }
}

/// Output length is bound into the hash, and the output buffer is written
/// exactly `out.len()` bytes at a non-zero offset.
#[test]
fn parallel_hash_output_length_binding_and_canaries() {
    let data = pattern(500, 0x33);
    for &out_len in &[0usize, 1, 7, 31, 32, 33, 63, 64, 65] {
        let expected = ref_parallel_hash(&data, 16, b"", out_len, false);

        let mut buffer = vec![0x5Au8; out_len + 24];
        ParallelHash256::hash(&data, 16, b"", &mut buffer[8..8 + out_len]).unwrap();
        assert_eq!(&buffer[8..8 + out_len], &expected[..], "out_len={out_len}");
        assert!(buffer[..8].iter().all(|&b| b == 0x5A), "front canary out_len={out_len}");
        assert!(
            buffer[8 + out_len..].iter().all(|&b| b == 0x5A),
            "back canary out_len={out_len}"
        );
    }
}

