//! Tests for the Keccak core, its per-target backends,
//! the batched permutation/shared sponge, and ParallelHash256.
//!
//! Everything here is checked against a small reference implementation written
//! from FIPS 202 and SP 800-185 in this file (round constants from the FIPS
//! LFSR, rotation offsets from the rho/pi walk, a byte-at-a-time sponge, and
//! the cSHAKE/ParallelHash definitions). The reference is itself pinned to
//! published XKCP and NIST vectors below, so it cannot silently become the
//! oracle for its own bug.
//!
//! `p1600`/`KeccakSponge` dispatch to the best backend for the target. On
//! aarch64 targets with SHA-3 that is the FEAT_SHA3 kernel; on x86-64 it is
//! AVX2/AVX-512 as selected by `PermuteBackend::detect`. The sweeps below
//! therefore execute the selected permutation for every rate and round count.

