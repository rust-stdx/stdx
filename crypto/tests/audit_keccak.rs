#[test]
fn shake128_and_shake256_match_reference_including_multi_block_output() {
    let cases: [(usize, usize, u64); 2] = [(168, 2 * 168 + 33, 0xaaaa), (136, 2 * 136 + 33, 0xbbbb)];
    for (rate, out_len, seed) in cases {
        let mut rng = ChaChaRng::seed_from_u64(seed);
        for len in 0..=(2 * rate + 32) {
            let data = {
                let mut v = vec![0u8; len];
                rng.fill(&mut v);
                v
            };
            let expected = ref_sponge::<24>(&data, rate, 0x1f, out_len);

            if rate == 168 {
                let mut out = vec![0u8; out_len];
                Shake128::hash(&data, &mut out);
                assert_eq!(out, expected, "SHAKE128 len={len}");

                let mut xof = Shake128::new();
                for part in data.chunks(1 + len % 17) {
                    xof.absorb(part);
                }
                let mut chunked = vec![0u8; out_len];
                let mut offset = 0;
                let mut index = 0;
                let sizes = [1usize, 7, 8, 63, 64, 65, 167, 168];
                while offset < out_len {
                    let take = core::cmp::min(sizes[index % sizes.len()], out_len - offset);
                    xof.squeeze(&mut chunked[offset..offset + take]);
                    offset += take;
                    index += 1;
                }
                assert_eq!(chunked, expected, "SHAKE128 incremental len={len}");
            } else {
                let mut out = vec![0u8; out_len];
                Shake256::hash(&data, &mut out);
                assert_eq!(out, expected, "SHAKE256 len={len}");

                let mut xof = Shake256::new();
                for part in data.chunks(1 + len % 19) {
                    xof.absorb(part);
                }
                let mut chunked = vec![0u8; out_len];
                let mut offset = 0;
                let mut index = 0;
                let sizes = [1usize, 9, 16, 64, 127, 136, 137];
                while offset < out_len {
                    let take = core::cmp::min(sizes[index % sizes.len()], out_len - offset);
                    xof.squeeze(&mut chunked[offset..offset + take]);
                    offset += take;
                    index += 1;
                }
                assert_eq!(chunked, expected, "SHAKE256 incremental len={len}");
            }
        }
    }
}

/// A few published one-shot vectors through the wrapper types, so a wrong
/// domain separator or output length cannot hide behind the reference.
#[test]
fn published_sha3_and_shake_vectors() {
    assert_eq!(
        hex::encode(Sha3_256::hash(b"").as_ref()),
        "a7ffc6f8bf1ed76651c14756a061d662f580ff4de43b49fa82d80a4b80f8434a"
    );
    assert_eq!(
        hex::encode(Sha3_512::hash(b"").as_ref()),
        "a69f73cca23a9ac5c8b567dc185a756e97c982164fe25859e0d1dcc1475c80a6\
         15b2123af1f5f94c11e3e9402c3ac558f500199d95b6d3e301758586281dcd26"
    );

    let mut out = [0u8; 32];
    Shake128::hash(b"", &mut out);
    assert_eq!(&hex::encode(out)[..32], "7f9c2ba4e88f827d616045507605853e");
    Shake256::hash(b"", &mut out);
    assert_eq!(&hex::encode(out)[..32], "46b9dd2b0ba88d13233b3feb743eeb24");

    // SP 800-185 cSHAKE256 sample 3: N = "", S = "Email Signature",
    // X = 00010203, L = 512.
    let mut out = [0u8; 64];
    let mut cshake = CShake256::new(b"", b"Email Signature");
    cshake.absorb(&[0u8, 1, 2, 3]);
    cshake.squeeze(&mut out);
    assert_eq!(
        hex::encode(out),
        "d008828e2b80ac9d2218ffee1d070c48b8e4c87bff32c9699d5b6896eee0edd1\
         64020e2be0560858d9c00c037e34a96937c561a74c412bb4c746469527281c8c"
    );
    assert_eq!(out[..], ref_cshake(&[0, 1, 2, 3], b"", b"Email Signature", 64)[..]);

    // TurboSHAKE256 uses the last twelve rounds and the same rate.
    let data = pattern(300, 1);
    let mut turbo = [0u8; 64];
    let mut xof = TurboShake256::new(0x1f).unwrap();
    xof.absorb(&data);
    xof.squeeze(&mut turbo);
    assert_eq!(turbo[..], ref_sponge::<12>(&data, 136, 0x1f, 64)[..]);

    // KT256 must not degenerate to a plain SHAKE256 of the same bytes.
    let mut kt = [0u8; 64];
    Kt256::hash(&data, b"", &mut kt);
    let mut shake = [0u8; 64];
    Shake256::hash(&data, &mut shake);
    assert_ne!(kt, shake);
}

