//! Known passkey authenticator AAGUIDs and their display names.
//!
//! Passkey providers identify themselves with an AAGUID embedded in the
//! registration attestation. This crate maps those AAGUIDs to a user-facing
//! name such as `"Bitwarden"`, so a client can label a passkey
//! without asking a server.
//!
//! The table is a frozen snapshot of the community
//! [passkey-authenticator-aaguids](https://github.com/passkeydeveloper/passkey-authenticator-aaguids)
//! list, pinned to commit `d53c0f358deeec6ba23d6c6e1f25f32ce45c22f9`. Only the
//! AAGUID to name mapping is kept: icons and other metadata are dropped so the
//! table stays small enough to embed in an embedded client.
//!
//! `aaguids.rs` is generated by `make -C stdx/passkey_aaguids update_data` and
//! checked in, so building this crate needs no network access and no build
//! script. The upstream list is deprecated, which is why the data is
//! pinned: refreshing always reproduces the same table instead of silently
//! emptying it. Newly released authenticators will therefore never appear here.
//!
//! # Examples
//!
//! ```
//! use uuid::Uuid;
//!
//! let google = Uuid::parse("ea9b8d66-4d01-1d21-3ce4-b6b48cb575d4").unwrap();
//! assert_eq!(passkey_aaguids::name(google), Some("Google Password Manager"));
//! assert_eq!(passkey_aaguids::name(Uuid::nil()), None);
//! ```
//!
//! # TODO:
//!
//! Migrate this directory to the FIDO Metadata Service
//! (<https://fidoalliance.org/metadata/>), which replaces the deprecated
//! https://github.com/passkeydeveloper/passkey-authenticator-aaguids
//!
#![no_std]

mod aaguids;

use uuid::Uuid;

use crate::aaguids::PASSKEY_MANAGERS;

/// A known passkey authenticator and its display name.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct PasskeyManager {
    /// The authenticator's AAGUID.
    pub aaguid: Uuid,
    /// The name to show to the user, for example `"Google Password Manager"`.
    pub name: &'static str,
}

/// Returns every known authenticator, ordered by AAGUID.
///
/// The slice is never empty: `make update_data` refuses to write a table
/// without named authenticators.
#[must_use]
pub fn managers() -> &'static [PasskeyManager] {
    PASSKEY_MANAGERS
}

/// Returns the display name registered for `aaguid`.
///
/// Returns `None` when the authenticator is not in the directory. Unknown
/// authenticators are the normal case: the list only covers providers that
/// were submitted to the community list before it was frozen.
#[must_use]
pub fn name(aaguid: Uuid) -> Option<&'static str> {
    let index = PASSKEY_MANAGERS
        .binary_search_by_key(&aaguid, |manager| manager.aaguid)
        .ok()?;
    Some(PASSKEY_MANAGERS[index].name)
}

/// Parses an AAGUID emitted by `make update_data`.
///
/// Because [`Uuid::parse`] is `const`, an invalid generated entry is a build
/// error instead of a runtime surprise.
const fn parse_aaguid(text: &str) -> Uuid {
    match Uuid::parse(text) {
        Ok(aaguid) => aaguid,
        Err(_) => panic!("generated AAGUID is not a canonical UUID"),
    }
}

/// Compares two AAGUIDs byte by byte, matching [`Uuid`]'s ordering.
const fn aaguid_less(left: Uuid, right: Uuid) -> bool {
    let left = left.as_bytes();
    let right = right.as_bytes();
    let mut index = 0;
    while index < left.len() {
        if left[index] != right[index] {
            return left[index] < right[index];
        }
        index += 1;
    }
    false
}

// The binary search in `name` relies on the generated table being sorted.
const _: () = {
    let mut index = 1;
    while index < PASSKEY_MANAGERS.len() {
        assert!(aaguid_less(PASSKEY_MANAGERS[index - 1].aaguid, PASSKEY_MANAGERS[index].aaguid));
        index += 1;
    }
};

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_authenticator() {
        let google = parse_aaguid("ea9b8d66-4d01-1d21-3ce4-b6b48cb575d4");
        assert_eq!(name(google), Some("Google Password Manager"));
    }

    #[test]
    fn unknown_authenticator() {
        assert_eq!(name(Uuid::nil()), None);
        assert_eq!(name(Uuid::max()), None);
    }

    #[test]
    fn directory_is_sorted_and_named() {
        assert!(managers().len() > 400, "unexpectedly small AAGUID directory");
        assert!(managers().windows(2).all(|pair| pair[0].aaguid < pair[1].aaguid));
        assert!(managers().iter().all(|manager| !manager.name.trim().is_empty()));
    }
}
