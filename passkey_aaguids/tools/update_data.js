#!/usr/bin/env node
// Regenerate `aaguids.rs` from a `combined_aaguid.json` snapshot of the
// community passkey AAGUID list.
//
// Usage:
//   node tools/update_data.js <combined_aaguid.json> <aaguids.rs>
//
// The upstream document stores a large amount of metadata per authenticator
// (notably base64 icons). Only the `name` field is kept, and the generated
// table is a slice sorted by AAGUID so lookups are a binary search at runtime.
//
// This script is normally run through `make update_data`, which fetches the
// pinned snapshot and formats the result. It exits non-zero, leaving the
// previous table untouched, when the document no longer contains enough named
// authenticators: the upstream list is deprecated and is emptied in 2027.

import { readFileSync, writeFileSync } from "node:fs";

// The snapshot every build of this crate is generated from.
const SOURCE_COMMIT = "d53c0f358deeec6ba23d6c6e1f25f32ce45c22f9";

// A truncated table means the upstream document was retired or replaced; fail
// loudly instead of silently shipping a directory that names nothing.
const MINIMUM_ENTRIES = 400;

const CANONICAL_AAGUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

function fail(message) {
  console.error(`update_data: ${message}`);
  process.exit(1);
}

// Formats `text` as a Rust string literal. Names contain quotes, backslashes
// and non-ASCII characters, so escaping is done explicitly instead of relying
// on `JSON.stringify`, whose `\/` escape Rust does not understand.
function rustString(text) {
  let out = '"';
  for (const char of text) {
    const codePoint = char.codePointAt(0);
    if (char === '"') {
      out += '\\"';
    } else if (char === "\\") {
      out += "\\\\";
    } else if (codePoint < 0x20 || codePoint === 0x7f) {
      out += `\\u{${codePoint.toString(16)}}`;
    } else {
      out += char;
    }
  }
  return `${out}"`;
}

function main() {
  const [inputPath, outputPath] = process.argv.slice(2);
  if (!inputPath || !outputPath) {
    fail("usage: node tools/update_data.js <combined_aaguid.json> <aaguids.rs>");
  }

  const upstream = JSON.parse(readFileSync(inputPath, "utf8"));
  if (upstream === null || typeof upstream !== "object" || Array.isArray(upstream)) {
    fail(`${inputPath} is not an object of AAGUIDs`);
  }

  const managers = [];
  for (const [aaguid, entry] of Object.entries(upstream)) {
    if (!CANONICAL_AAGUID.test(aaguid)) {
      fail(`${inputPath} contains a non-canonical AAGUID: ${aaguid}`);
    }
    const name = typeof entry?.name === "string" ? entry.name.trim() : "";
    if (name.length > 0) {
      managers.push({ aaguid, name });
    }
  }

  if (managers.length < MINIMUM_ENTRIES) {
    fail(`${inputPath} contains ${managers.length} named AAGUIDs but ${MINIMUM_ENTRIES} are expected; the upstream list may have been retired`);
  }

  // Canonical lowercase AAGUIDs sort lexicographically in the same order as
  // their bytes, which is what the crate's binary search and ordering check
  // rely on.
  managers.sort((left, right) => (left.aaguid < right.aaguid ? -1 : 1));

  const lines = [
    "// @generated by passkey_aaguids/tools/update_data.js. Do not edit.",
    "//",
    `// Source: \`combined_aaguid.json\` at commit ${SOURCE_COMMIT} of`,
    "// <https://github.com/passkeydeveloper/passkey-authenticator-aaguids>.",
    "// Refresh with `make -C stdx/passkey_aaguids update_data`.",
    "",
    "use crate::{PasskeyManager, parse_aaguid};",
    "",
    "// Generated one entry per line: the table is data, not code to reflow.",
    "#[rustfmt::skip]",
    "pub(super) const PASSKEY_MANAGERS: &[PasskeyManager] = &[",
    ...managers.map(
      (manager) =>
        `    PasskeyManager { aaguid: parse_aaguid(${rustString(manager.aaguid)}), name: ${rustString(manager.name)} },`,
    ),
    "];",
    "",
  ];

  writeFileSync(outputPath, lines.join("\n"));
  console.error(`update_data: wrote ${managers.length} AAGUIDs to ${outputPath}`);
}

main();
