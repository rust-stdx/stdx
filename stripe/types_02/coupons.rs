impl<'json> json::Decode<'json> for CouponObject {
    fn decode(decoder: &mut json::Decoder<'json>) -> json::Result<Self> {
        decoder.skip_ws()?;
        if decoder.peek_byte() == Some(b'n') {
            decoder.decode_null()?;
            return Ok(CouponObject::Unknown(String::new()));
        }
        let value = decoder.decode_string()?;
        Ok(match value.as_str() {
            "coupon" => CouponObject::Coupon,
            other => CouponObject::Unknown(other.to_string()),
        })
    }
}

#[cfg(feature = "coupons")]
#[derive(Debug, Clone, Default)]
pub struct CreateCouponParamsAppliesTo {
    #[doc = "An array of Product IDs that this Coupon will apply to."]
    pub products: Option<Vec<String>>,
}

#[cfg(feature = "coupons")]
impl crate::params::FormEncode for CreateCouponParamsAppliesTo {
    fn encode_form(&self, form: &mut crate::params::FormBuilder) {
        if let Some(values) = self.products.as_ref() {
            form.field_array("products", values.as_slice());
        }
    }
}
