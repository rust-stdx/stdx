#[cfg(feature = "plans")]
#[derive(Debug, Clone)]
pub struct CreatePlanParams {
    #[doc = "Whether the plan is currently available for new subscriptions."]
    pub active: Option<bool>,
    #[doc = "A positive integer in cents (or local equivalent) (or 0 for a free plan) representing how much to charge on a recurri..."]
    pub amount: Option<i64>,
    #[doc = "Same as `amount`, but accepts a decimal value with at most 12 decimal places."]
    pub amount_decimal: Option<String>,
    #[doc = "Describes how to compute the price per period."]
    pub billing_scheme: Option<stripe_types_03::plans::CreatePlanParamsBillingScheme>,
    #[doc = "Three-letter [ISO currency code](https://www.iso.org/iso-4217-currency-codes.html), in lowercase."]
    pub currency: String,
    #[doc = "Specifies which fields in the response should be expanded."]
    pub expand: Option<Vec<String>>,
    #[doc = "An identifier randomly generated by Stripe."]
    pub id: Option<String>,
    #[doc = "Specifies billing frequency."]
    pub interval: stripe_types_00::plans::CreatePlanParamsInterval,
    #[doc = "The number of intervals between subscription billings."]
    pub interval_count: Option<i64>,
    #[doc = "Set of [key-value pairs](https://docs.stripe.com/api/metadata) that you can attach to an object."]
    pub metadata: Option<std::collections::HashMap<String, String>>,
    #[doc = "The meter tracking the usage of a metered price"]
    pub meter: Option<String>,
    #[doc = "A brief description of the plan, hidden from customers."]
    pub nickname: Option<String>,
    pub product: Option<stripe_types_05::plans::CreatePlanParamsProduct>,
    #[doc = "Each element represents a pricing tier."]
    pub tiers: Option<Vec<stripe_types_00::plans::CreatePlanParamsTiersItem>>,
    #[doc = "Defines if the tiering price should be `graduated` or `volume` based."]
    pub tiers_mode: Option<stripe_types_03::plans::CreatePlanParamsTiersMode>,
    #[doc = "Apply a transformation to the reported usage or set quantity before computing the billed price."]
    pub transform_usage: Option<stripe_types_05::plans::CreatePlanParamsTransformUsage>,
    #[doc = "Default number of trial days when subscribing a customer to this plan using `trial_from_plan=true`..."]
    pub trial_period_days: Option<i64>,
    #[doc = "Configures how the quantity per period should be determined."]
    pub usage_type: Option<stripe_types_04::plans::CreatePlanParamsUsageType>,
}

#[cfg(feature = "plans")]
impl crate::params::FormEncode for CreatePlanParams {
    fn encode_form(&self, form: &mut crate::params::FormBuilder) {
        form.field_opt("active", self.active.as_ref());
        form.field_opt("amount", self.amount.as_ref());
        form.field_opt("amount_decimal", self.amount_decimal.as_ref());
        form.field_opt("billing_scheme", self.billing_scheme.as_ref());
        form.field("currency", &self.currency);
        if let Some(values) = self.expand.as_ref() {
            form.field_array("expand", values.as_slice());
        }
        form.field_opt("id", self.id.as_ref());
        form.field("interval", &self.interval);
        form.field_opt("interval_count", self.interval_count.as_ref());
        if let Some(values) = self.metadata.as_ref() {
            for (key, value) in values.iter() {
                form.field_map("metadata", key, value);
            }
        }
        form.field_opt("meter", self.meter.as_ref());
        form.field_opt("nickname", self.nickname.as_ref());
        form.field_opt("product", self.product.as_ref());
        if let Some(values) = self.tiers.as_ref() {
            for (index, item) in values.iter().enumerate() {
                form.field_indexed("tiers", index, item);
            }
        }
        form.field_opt("tiers_mode", self.tiers_mode.as_ref());
        form.field_opt("transform_usage", self.transform_usage.as_ref());
        form.field_opt("trial_period_days", self.trial_period_days.as_ref());
        form.field_opt("usage_type", self.usage_type.as_ref());
    }
}
