#[cfg(feature = "products")]
impl crate::params::FormEncode for CreateProductParams {
    fn encode_form(&self, form: &mut crate::params::FormBuilder) {
        form.field_opt("active", self.active.as_ref());
        form.field_opt("default_price_data", self.default_price_data.as_ref());
        form.field_opt("description", self.description.as_ref());
        if let Some(values) = self.expand.as_ref() {
            form.field_array("expand", values.as_slice());
        }
        form.field_opt("id", self.id.as_ref());
        if let Some(values) = self.images.as_ref() {
            form.field_array("images", values.as_slice());
        }
        if let Some(values) = self.marketing_features.as_ref() {
            for (index, item) in values.iter().enumerate() {
                form.field_indexed("marketing_features", index, item);
            }
        }
        if let Some(values) = self.metadata.as_ref() {
            for (key, value) in values.iter() {
                form.field_map("metadata", key, value);
            }
        }
        form.field("name", &self.name);
        form.field_opt("package_dimensions", self.package_dimensions.as_ref());
        form.field_opt("shippable", self.shippable.as_ref());
        form.field_opt("statement_descriptor", self.statement_descriptor.as_ref());
        form.field_opt("tax_code", self.tax_code.as_ref());
        form.field_opt("tax_details", self.tax_details.as_ref());
        form.field_opt("type", self.r#type.as_ref());
        form.field_opt("unit_label", self.unit_label.as_ref());
        form.field_opt("url", self.url.as_ref());
    }
}

