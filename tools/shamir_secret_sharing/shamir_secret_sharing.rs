    fn payload(version: u8, threshold: u8, index: u8, data: &[u8]) -> Vec<u8> {
        let mut payload = vec![version, threshold, index];
        payload.extend_from_slice(data);
        let check = checksum(&payload);
        payload.extend_from_slice(&check);
        return payload;
    }

    fn encode_payload(payload: &[u8], alphabet: Alphabet) -> String {
        return encode(payload, alphabet);
    }

    fn share_refs(shares: &[Share]) -> Vec<&Share> {
        return shares.iter().collect();
    }

    fn combinations(total: usize, count: usize) -> Vec<Vec<usize>> {
        fn walk(start: usize, total: usize, count: usize, current: &mut Vec<usize>, out: &mut Vec<Vec<usize>>) {
            if current.len() == count {
                out.push(current.clone());
                return;
            }
            let remaining = count - current.len();
            for index in start..=total - remaining {
                current.push(index);
                walk(index + 1, total, count, current, out);
                current.pop();
            }
        }

        let mut out = Vec::new();
        walk(0, total, count, &mut Vec::new(), &mut out);
        return out;
    }

