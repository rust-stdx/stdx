    #[test]
    fn gf_mul_is_commutative_associative_and_distributive() {
        let samples = [0x00u8, 0x01, 0x02, 0x57, 0x80, 0xa5, 0xfe, 0xff];
        for &a in &samples {
            for &b in &samples {
                assert_eq!(gf_mul(a, b), gf_mul(b, a), "commutativity for {a:#04x}, {b:#04x}");
                for &c in &samples {
                    assert_eq!(
                        gf_mul(gf_mul(a, b), c),
                        gf_mul(a, gf_mul(b, c)),
                        "associativity for {a:#04x}, {b:#04x}, {c:#04x}"
                    );
                    assert_eq!(
                        gf_mul(a, b ^ c),
                        gf_mul(a, b) ^ gf_mul(a, c),
                        "distributivity for {a:#04x}, {b:#04x}, {c:#04x}"
                    );
                }
            }
        }
    }

