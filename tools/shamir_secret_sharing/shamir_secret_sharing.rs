//! Shamir secret sharing over GF(256), as a command-line tool.
//!
//! `shamir_secret_sharing` splits a secret into `n` shares such that any `t`
//! shares reconstruct it, while any `t - 1` shares reveal nothing about it.
//! Shares are printed as base64 strings; the payload carried inside the base64
//! is raw binary data.
//!
//! # Usage
//!
//! ```text
//! shamir_secret_sharing split [-n <shares>] [-t <threshold>] [-r[BYTES] | --random[=BYTES]]
//! shamir_secret_sharing combine
//! ```
//!
//! `split` prompts for the secret (twice, without echo) unless `--random` is
//! used. With `--random`, a random secret of the requested length (32 bytes by
//! default) is generated and printed as `secret: <base64>` before the shares.
//! Shares are printed one bare base64 string per line, so they can be copied
//! into separate files. `combine` prompts for shares without echo, which also
//! works when the shares are piped in on standard input; it ignores a
//! `secret: <base64>` line so the whole output of `split --random` can be fed
//! back into it.
//!
//! # Share format
//!
//! Each share decodes to:
//!
//! ```text
//! [0]    version (1)
//! [1]    threshold t
//! [2]    share index x (1..=255)
//! [3..]  share bytes (the same length as the secret)
//! [-4..] first 4 bytes of SHAKE256 over everything before it
//! ```
//!
//! The checksum detects accidental corruption (a mistyped or truncated share).
//! It is not a MAC and provides no protection against a deliberate modification
//! of a share. It also cannot tell that shares come from different splits:
//! combining unrelated shares yields a meaningless secret rather than an error.
//!
//! # Security notes
//!
//! * Confidentiality holds only while fewer than `t` shares are available to an
//!   attacker. Anyone holding `t` shares can recover the secret; there is no
//!   additional authentication.
//! * Shares, coefficients and reconstructed secrets are held in zeroizing
//!   buffers, so they are cleared when dropped. The process can still leave
//!   copies in the allocator, in the terminal scrollback (if the secret is
//!   pasted), and in shell history (shares presented as command-line
//!   arguments). `combine` deliberately reads shares from stdin instead of
//!   taking them as arguments.
//! * The GF(256) arithmetic uses no tables indexed by secret data and the
//!   inversion is a fixed-exponent field exponentiation, so the byte-level
//!   operations are branch-free with respect to the secret. This is a
//!   best-effort mitigation: the CLI is intended for use on a trusted machine.
//! * A secret longer than 1 MiB is rejected to keep accidental allocations
//!   bounded.

use std::{
    env,
    io::{self, BufRead, IsTerminal, Write},
    process,
};

use base64::{Alphabet, decode, encode};
use crypto::{random, sha3::Shake256};
use getopts::{Matches, Options};
use zeroize::Zeroizing;

/// Version byte stored in every share payload.
const VERSION: u8 = 1;
/// Number of leading payload bytes before the share data: version, threshold and index.
const HEADER_LENGTH: usize = 3;
/// Number of trailing SHAKE256 bytes used as a transcription check.
const CHECKSUM_LENGTH: usize = 4;
/// Number of bytes generated by `--random` when no length is given.
const DEFAULT_RANDOM_SECRET_LENGTH: usize = 32;
/// Upper bound for a secret, in bytes, accepted by `split` and `combine`.
const MAX_SECRET_LENGTH: usize = 1024 * 1024;
/// Number of shares generated when `-n` is not given.
const DEFAULT_SHARES: u8 = 3;
/// Smallest useful number of shares.
const MIN_SHARES: u8 = 2;
/// GF(256) can only represent share indices 1..=255.
const MAX_SHARES: u8 = u8::MAX;
/// The GF(256) reduction polynomial x^8 + x^4 + x^3 + x + 1, without the x^8 bit.
const GF_POLYNOMIAL: u8 = 0x1b;

type Result<T> = std::result::Result<T, String>;

/// One Shamir share: a share index `x` and the polynomial evaluation at that `x`.
struct Share {
    index: u8,
    data: Zeroizing<Vec<u8>>,
}

impl Share {
    fn new(index: u8, data: Vec<u8>) -> Self {
        return Self {
            index,
            data: Zeroizing::new(data),
        };
    }
}

/// A share together with the threshold of the split it came from.
struct ParsedShare {
    threshold: u8,
    share: Share,
}

fn main() {
    if let Err(error) = run() {
        eprintln!("error: {error}");
        process::exit(1);
    }
}

fn run() -> Result<()> {
    let mut arguments = env::args();
    let program = arguments
        .next()
        .unwrap_or_else(|| String::from("shamir_secret_sharing"));
    let mut arguments: Vec<String> = arguments.collect();

    let Some(command) = arguments.first().cloned() else {
        return Err(format!("missing command\n\n{}", usage(&program)));
    };
    arguments.remove(0);

    return match command.as_str() {
        "split" => cmd_split(&program, &arguments),
        "combine" => cmd_combine(&program, &arguments),
        "-h" | "--help" | "help" => {
            println!("{}", usage(&program));
            Ok(())
        }
        other => Err(format!("unknown command '{other}': expected 'split' or 'combine'")),
    };
}

fn usage(program: &str) -> String {
    return format!(
        "Usage:\n  {program} split [-n <shares>] [-t <threshold>] [-r[BYTES] | --random[=BYTES]]\n  {program} combine\n\n\
         Commands:\n  split    Generate base64-encoded shares of a secret.\n  combine  Reconstruct the secret from base64-encoded shares.\n\n\
         Run '{program} split --help' or '{program} combine --help' for the options of a command."
    );
}

fn cmd_split(program: &str, args: &[String]) -> Result<()> {
    let mut options = Options::new();
    options.optopt("n", "shares", "total number of shares to generate (2-255, default 3)", "N");
    options.optopt(
        "t",
        "threshold",
        "shares required to reconstruct (default: 2 when n <= 3, otherwise 3)",
        "T",
    );
    options.optflagopt(
        "r",
        "random",
        "use a generated random secret instead of prompting; the optional value is its length in bytes (default 32)",
        "BYTES",
    );
    options.optflag("h", "help", "print this help");

    let args = normalize_split_args(args);
    let matches = options.parse(&args).map_err(|error| error.to_string())?;
    if matches.opt_present("h") {
        print_help(program, "split", &options);
        return Ok(());
    }
    if let Some(free) = matches.free.first() {
        return Err(format!("unexpected argument '{free}' for split"));
    }

    let shares = parse_shares(&matches)?;
    let threshold = parse_threshold(&matches, shares)?;
    let random_length = if matches.opt_present("r") {
        Some(parse_random_length(matches.opt_str("r").as_deref())?)
    } else {
        None
    };

    let secret = match random_length {
        Some(length) => {
            let mut secret = Zeroizing::new(vec![0u8; length]);
            random::fill(secret.as_mut_slice())
                .map_err(|error| format!("failed to generate a random secret: {error}"))?;
            secret
        }
        None => read_typed_secret()?,
    };

    let shares = split_secret(secret.as_slice(), shares, threshold)?;
    verify_split(secret.as_slice(), &shares, threshold)?;

    let stdout = io::stdout();
    let mut output = stdout.lock();

    if random_length.is_some() {
        let encoded_secret = Zeroizing::new(encode(secret.as_slice(), Alphabet::Standard));
        writeln!(output, "secret: {}", encoded_secret.as_str()).map_err(write_error)?;
    }
    for share in &shares {
        let encoded_share = Zeroizing::new(encode_share(share, threshold));
        writeln!(output, "{}", encoded_share.as_str()).map_err(write_error)?;
    }
    output.flush().map_err(write_error)?;

    return Ok(());
}

fn cmd_combine(program: &str, args: &[String]) -> Result<()> {
    let mut options = Options::new();
    options.optflag("h", "help", "print this help");

    let matches = options.parse(args).map_err(|error| error.to_string())?;
    if matches.opt_present("h") {
        print_help(program, "combine", &options);
        return Ok(());
    }
    if let Some(free) = matches.free.first() {
        return Err(format!(
            "unexpected argument '{free}' for combine: shares are read from standard input"
        ));
    }

    let mut shares: Vec<Share> = Vec::new();
    let mut threshold = None;
    let mut length = None;

    loop {
        // The threshold is carried by every share, so the first one tells us how
        // many prompts are needed. Read exactly the threshold rather than waiting
        // for EOF, which keeps `combine` usable in a pipeline.
        if threshold.is_some_and(|threshold: u8| shares.len() >= threshold as usize) {
            break;
        }

        let line = prompt_hidden(&format!("Share {}: ", shares.len() + 1))?;
        let line = line.trim();
        if line.is_empty() {
            // Empty input or EOF. If enough shares were already read the loop
            // would have stopped above, so this is always an error.
            break;
        }
        if is_secret_line(line) {
            continue;
        }

        let parsed = decode_share(line)?;
        match threshold {
            None => {
                threshold = Some(parsed.threshold);
                length = Some(parsed.share.data.len());
            }
            Some(expected) => {
                if parsed.threshold != expected {
                    return Err(format!(
                        "share {} uses threshold {}, but previous shares use threshold {expected}",
                        parsed.share.index, parsed.threshold
                    ));
                }
                if Some(parsed.share.data.len()) != length {
                    return Err(format!(
                        "share {} has a different length than the previous shares",
                        parsed.share.index
                    ));
                }
            }
        }

        if shares.iter().any(|share| share.index == parsed.share.index) {
            return Err(format!("duplicate share index {}", parsed.share.index));
        }
        shares.push(parsed.share);
    }

    let Some(threshold) = threshold else {
        return Err("no shares were provided".into());
    };
    if shares.len() < threshold as usize {
        return Err(format!("not enough shares: got {}, need at least {threshold}", shares.len()));
    }

    let share_refs: Vec<&Share> = shares.iter().collect();
    let secret = combine_secret(&share_refs)?;

    let stdout = io::stdout();
    let mut output = stdout.lock();
    output.write_all(secret.as_slice()).map_err(write_error)?;
    output.flush().map_err(write_error)?;
    drop(output);
    // Keep the shell prompt on its own line without adding bytes to stdout,
    // which must contain exactly the reconstructed secret.
    eprintln!();

    return Ok(());
}

/// Accepts `--random N` in addition to the forms understood by `getopts`
/// (`--random=N`, `-r N`, `-rN`).
///
/// `getopts` follows GNU getopt for options with an optional argument and does
/// not consume a separate token after a long option. Rewriting only that one
/// form keeps the rest of the parsing (including `--`) untouched.
fn normalize_split_args(args: &[String]) -> Vec<String> {
    let mut normalized = Vec::with_capacity(args.len());
    let mut index = 0;

    while index < args.len() {
        if args[index] == "--" {
            normalized.extend_from_slice(&args[index..]);
            break;
        }

        if args[index] == "--random" {
            match args.get(index + 1) {
                Some(next) if next.parse::<usize>().is_ok() => {
                    normalized.push(format!("--random={next}"));
                    index += 2;
                    continue;
                }
                _ => {
                    normalized.push(String::from("--random"));
                    index += 1;
                    continue;
                }
            }
        }

        normalized.push(args[index].clone());
        index += 1;
    }

    return normalized;
}

fn print_help(program: &str, command: &str, options: &Options) {
    let brief = format!("Usage: {program} {command} [options]");
    let mut stdout = io::stdout().lock();
    let _ = write!(stdout, "{}", options.usage(&brief));
}

fn write_error(error: io::Error) -> String {
    return format!("failed to write output: {error}");
}

fn read_typed_secret() -> Result<Zeroizing<Vec<u8>>> {
    let secret = prompt_hidden("Secret: ")?;
    if secret.is_empty() {
        return Err("secret is empty".into());
    }

    let confirmation = prompt_hidden("Confirm secret: ")?;
    if secret.as_str() != confirmation.as_str() {
        return Err("secrets don't match".into());
    }

    return Ok(Zeroizing::new(secret.as_bytes().to_vec()));
}

/// Prints `prompt` to stderr and reads one line from stdin.
///
/// On a terminal the line is read with echo disabled by [`term`], so a pasted
/// secret or share is not displayed. When stdin is a pipe the line is read
/// directly, which also accepts CRLF input and needs no echo suppression. The
/// value is wrapped in [`Zeroizing`] so the buffer is cleared when the caller is
/// done with it; an empty result usually means end of input.
fn prompt_hidden(prompt: &str) -> Result<Zeroizing<String>> {
    eprint!("{prompt}");
    io::stderr().flush().map_err(write_error)?;

    let value = if io::stdin().is_terminal() {
        term::read_password().map_err(|error| format!("failed to read from the terminal: {error}"))?
    } else {
        read_piped_line()?
    };

    eprintln!();
    return Ok(Zeroizing::new(value));
}

/// Reads one line from a non-terminal stdin and strips a trailing CR and/or LF.
fn read_piped_line() -> Result<String> {
    let mut line = Zeroizing::new(String::new());
    let bytes = io::stdin()
        .lock()
        .read_line(&mut line)
        .map_err(|error| format!("failed to read standard input: {error}"))?;
    if bytes == 0 {
        return Ok(String::new());
    }
    return Ok(line.trim_end_matches(['\r', '\n']).to_string());
}

fn parse_shares(matches: &Matches) -> Result<u8> {
    let Some(value) = matches.opt_str("n") else {
        return Ok(DEFAULT_SHARES);
    };
    let shares: u8 = value.parse().map_err(|_| {
        format!("invalid -n value '{value}': expected an integer between {MIN_SHARES} and {MAX_SHARES}")
    })?;
    if shares < MIN_SHARES {
        return Err(format!(
            "invalid -n value '{value}': expected an integer between {MIN_SHARES} and {MAX_SHARES}"
        ));
    }
    return Ok(shares);
}

fn parse_threshold(matches: &Matches, shares: u8) -> Result<u8> {
    let Some(value) = matches.opt_str("t") else {
        return Ok(default_threshold(shares));
    };
    let threshold: u8 = value
        .parse()
        .map_err(|_| format!("invalid -t value '{value}': expected an integer between 1 and {shares}"))?;
    if threshold == 0 || threshold > shares {
        return Err(format!(
            "invalid -t value '{value}': expected an integer between 1 and {shares}"
        ));
    }
    return Ok(threshold);
}

/// Default threshold: 2 for very small splits, otherwise 3.
fn default_threshold(shares: u8) -> u8 {
    if shares <= 3 { 2 } else { 3 }
}

fn parse_random_length(value: Option<&str>) -> Result<usize> {
    let Some(value) = value else {
        return Ok(DEFAULT_RANDOM_SECRET_LENGTH);
    };
    let length: usize = value.parse().map_err(|_| {
        format!("invalid --random length '{value}': expected an integer between 1 and {MAX_SECRET_LENGTH}")
    })?;
    if !(1..=MAX_SECRET_LENGTH).contains(&length) {
        return Err(format!(
            "invalid --random length '{value}': expected an integer between 1 and {MAX_SECRET_LENGTH}"
        ));
    }
    return Ok(length);
}

fn validate_split(shares: u8, threshold: u8) -> Result<()> {
    if !(MIN_SHARES..=MAX_SHARES).contains(&shares) {
        return Err(format!("number of shares must be between {MIN_SHARES} and {MAX_SHARES}"));
    }
    if threshold == 0 || threshold > shares {
        return Err(format!("threshold must be between 1 and {shares}"));
    }
    return Ok(());
}

/// Splits `secret` into `shares` shares with the given `threshold`.
///
/// Each secret byte is the constant term of its own random polynomial of degree
/// `threshold - 1`; share `x` contains the polynomial evaluated at `x` for every
/// byte. The result is a vector of exactly `shares` shares with indices
/// `1..=shares`.
///
/// # Errors
///
/// Returns an error when `shares` is outside `2..=255`, when `threshold` is `0`
/// or greater than `shares`, or when the operating system's random number
/// generator fails.
fn split_secret(secret: &[u8], shares: u8, threshold: u8) -> Result<Vec<Share>> {
    validate_split(shares, threshold)?;
    if secret.len() > MAX_SECRET_LENGTH {
        return Err(format!("secret is too long: maximum length is {MAX_SECRET_LENGTH} bytes"));
    }

    let mut result: Vec<Share> = (1..=shares)
        .map(|index| Share::new(index, vec![0u8; secret.len()]))
        .collect();

    let mut coefficients = Zeroizing::new(vec![0u8; threshold as usize]);
    for (position, &byte) in secret.iter().enumerate() {
        coefficients[0] = byte;
        if coefficients.len() > 1 {
            random::fill(&mut coefficients[1..])
                .map_err(|error| format!("failed to generate random coefficients: {error}"))?;
        }
        for share in &mut result {
            share.data[position] = gf_eval(&coefficients, share.index);
        }
    }

    return Ok(result);
}

/// Reconstructs the secret from `shares` by Lagrange interpolation at `x = 0`.
///
/// The caller must provide at least `threshold` shares from the same split, but
/// this function does not know the threshold; it interpolates a polynomial of
/// degree `shares.len() - 1` through the given points. Passing fewer shares than
/// the threshold yields a value that is unrelated to the secret.
///
/// # Errors
///
/// Returns an error when no shares are given, when the shares have different
/// lengths, or when two shares use the same index. An empty secret is valid and
/// reconstructs to an empty result.
fn combine_secret(shares: &[&Share]) -> Result<Zeroizing<Vec<u8>>> {
    let Some(first) = shares.first() else {
        return Err("no shares provided".into());
    };

    let length = first.data.len();
    if shares.iter().any(|share| share.data.len() != length) {
        return Err("shares have different lengths".into());
    }

    let mut secret = Zeroizing::new(vec![0u8; length]);
    for (i, share) in shares.iter().enumerate() {
        let mut coefficient = 1u8;
        for (j, other) in shares.iter().enumerate() {
            if i == j {
                continue;
            }
            if share.index == other.index {
                return Err(format!("duplicate share index {}", share.index));
            }
            let denominator = other.index ^ share.index;
            coefficient = gf_mul(coefficient, gf_mul(other.index, gf_inv(denominator)));
        }

        for (output, &byte) in secret.iter_mut().zip(share.data.iter()) {
            *output ^= gf_mul(coefficient, byte);
        }
    }

    return Ok(secret);
}

/// Re-splits nothing; it verifies that a random threshold-sized subset of the
/// freshly generated shares reconstructs the original secret.
fn verify_split(secret: &[u8], shares: &[Share], threshold: u8) -> Result<()> {
    let selected = random_subset(shares.len(), threshold as usize)?;
    let subset: Vec<&Share> = selected.iter().map(|&index| &shares[index]).collect();
    let recovered = combine_secret(&subset)?;
    if recovered.as_slice() != secret {
        return Err(String::from(
            "internal error: the generated shares failed the reconstruction self-check",
        ));
    }
    return Ok(());
}

/// Picks `count` distinct indices in `0..total` using rejection sampling.
fn random_subset(total: usize, count: usize) -> Result<Vec<usize>> {
    let mut selected = Vec::with_capacity(count);
    while selected.len() < count {
        let [candidate] = random::bytes::<1>().map_err(|error| format!("failed to generate randomness: {error}"))?;
        let candidate = candidate as usize;
        if candidate >= total || selected.contains(&candidate) {
            continue;
        }
        selected.push(candidate);
    }
    return Ok(selected);
}

/// Appends a header, the share data and a SHAKE256 checksum, then base64-encodes it.
fn encode_share(share: &Share, threshold: u8) -> String {
    let mut payload = Zeroizing::new(Vec::with_capacity(HEADER_LENGTH + share.data.len() + CHECKSUM_LENGTH));
    payload.push(VERSION);
    payload.push(threshold);
    payload.push(share.index);
    payload.extend_from_slice(&share.data);

    let check = checksum(&payload);
    payload.extend_from_slice(&check);

    return encode(payload.as_slice(), Alphabet::Standard);
}

/// Decodes and validates a base64 share.
///
/// Both padded and unpadded standard base64 are accepted, and surrounding
/// whitespace is ignored.
///
/// # Errors
///
/// Returns an error when the input is not base64, is shorter than the header and
/// checksum, has a bad checksum, uses an unsupported version, has a threshold or
/// index of zero, or carries more than [`MAX_SECRET_LENGTH`] bytes of share data.
fn decode_share(encoded: &str) -> Result<ParsedShare> {
    let encoded = encoded.trim();
    if encoded.is_empty() {
        return Err("share is empty".into());
    }
    if encoded.len() > max_encoded_share_length() {
        return Err(String::from("share is too long"));
    }

    let payload = Zeroizing::new(decode_payload(encoded)?);
    let minimum = HEADER_LENGTH + CHECKSUM_LENGTH;
    if payload.len() < minimum {
        return Err(format!(
            "share is too short: expected at least {minimum} decoded bytes, got {}",
            payload.len()
        ));
    }

    let body_length = payload.len() - CHECKSUM_LENGTH;
    let threshold;
    let index;
    {
        let (body, check) = payload.split_at(body_length);
        if checksum(body).as_slice() != check {
            return Err(String::from("share checksum mismatch: the share is corrupted or was mistyped"));
        }
        if body[0] != VERSION {
            return Err(format!("unsupported share version {}: expected {VERSION}", body[0]));
        }
        threshold = body[1];
        index = body[2];
        if threshold == 0 {
            return Err(String::from("share has a threshold of 0"));
        }
        if index == 0 {
            return Err(String::from("share has an index of 0"));
        }
    }

    let data_length = body_length - HEADER_LENGTH;
    if data_length > MAX_SECRET_LENGTH {
        return Err(format!("share data is too long: maximum length is {MAX_SECRET_LENGTH} bytes"));
    }

    let data = Zeroizing::new(payload[HEADER_LENGTH..body_length].to_vec());

    return Ok(ParsedShare {
        threshold,
        share: Share {
            index,
            data,
        },
    });
}

fn decode_payload(encoded: &str) -> Result<Vec<u8>> {
    return match decode(encoded, Alphabet::Standard) {
        Ok(payload) => Ok(payload),
        Err(_) => {
            decode(encoded, Alphabet::StandardNoPadding).map_err(|error| format!("share is not valid base64: {error}"))
        }
    };
}

fn max_encoded_share_length() -> usize {
    return base64::encoded_length(HEADER_LENGTH + MAX_SECRET_LENGTH + CHECKSUM_LENGTH, true).unwrap_or(usize::MAX);
}

fn checksum(payload: &[u8]) -> [u8; CHECKSUM_LENGTH] {
    let mut result = [0u8; CHECKSUM_LENGTH];
    Shake256::hash(payload, &mut result);
    return result;
}

fn is_secret_line(line: &str) -> bool {
    return line.trim_start().starts_with("secret:");
}

/// Multiplies two GF(256) elements modulo x^8 + x^4 + x^3 + x + 1.
///
/// The implementation is the branch-free shift-and-XOR loop from the AES
/// specification: there are no lookup tables indexed by `a` or `b`.
#[inline]
fn gf_mul(mut a: u8, mut b: u8) -> u8 {
    let mut product = 0u8;
    let mut bit = 0;
    while bit < 8 {
        product ^= a & 0u8.wrapping_sub(b & 1);
        let carry = a >> 7;
        a = (a << 1) ^ (GF_POLYNOMIAL & 0u8.wrapping_sub(carry));
        b >>= 1;
        bit += 1;
    }
    return product;
}

/// Raises a GF(256) element to a public exponent with square-and-multiply.
#[inline]
fn gf_pow(mut base: u8, mut exponent: u8) -> u8 {
    let mut result = 1u8;
    let mut bit = 0;
    while bit < 8 {
        if exponent & 1 == 1 {
            result = gf_mul(result, base);
        }
        base = gf_mul(base, base);
        exponent >>= 1;
        bit += 1;
    }
    return result;
}

/// Multiplicative inverse in GF(256): `a^254` for a non-zero `a`.
///
/// Zero has no inverse; passing zero returns zero, which never happens for the
/// interpolated denominators because share indices are distinct and non-zero.
#[inline]
fn gf_inv(value: u8) -> u8 {
    return gf_pow(value, 254);
}

/// Evaluates a polynomial whose constant term is `coefficients[0]` at `x`.
fn gf_eval(coefficients: &[u8], x: u8) -> u8 {
    let mut value = 0u8;
    for &coefficient in coefficients.iter().rev() {
        value = gf_mul(value, x) ^ coefficient;
    }
    return value;
}

