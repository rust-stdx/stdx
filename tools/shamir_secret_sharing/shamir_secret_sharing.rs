    #[test]
    fn every_threshold_subset_reconstructs_the_secret() {
        let lengths = [
            0usize, 1, 2, 3, 4, 5, 15, 16, 17, 31, 32, 33, 47, 48, 49, 135, 136, 137, 255, 256,
        ];
        let parameters = [(2u8, 1u8), (2, 2), (3, 2), (3, 3), (4, 2), (5, 3), (6, 4), (8, 5)];

        for &length in &lengths {
            let secret: Vec<u8> = (0..length)
                .map(|position| (position as u8).wrapping_mul(37).wrapping_add(11))
                .collect();

            for &(shares_count, threshold) in &parameters {
                let shares = split_secret(&secret, shares_count, threshold).unwrap();
                for combination in combinations(shares_count as usize, threshold as usize) {
                    let subset: Vec<&Share> = combination.iter().map(|&index| &shares[index]).collect();
                    let recovered = combine_secret(&subset).unwrap();
                    assert_eq!(
                        recovered.as_slice(),
                        secret.as_slice(),
                        "length {length}, n {shares_count}, t {threshold}, subset {combination:?}"
                    );
                }
            }
        }
    }

    #[test]
    fn more_than_threshold_shares_and_any_order_reconstruct_the_secret() {
        let secret = b"order independence";
        for &(shares_count, threshold) in &[(3u8, 2u8), (5, 3), (8, 4), (10, 10)] {
            let shares = split_secret(secret, shares_count, threshold).unwrap();

            let mut all_shares = share_refs(&shares);
            let recovered = combine_secret(&all_shares).unwrap();
            assert_eq!(recovered.as_slice(), secret, "n {shares_count}, t {threshold}");

            all_shares.reverse();
            let recovered = combine_secret(&all_shares).unwrap();
            assert_eq!(recovered.as_slice(), secret, "reversed n {shares_count}, t {threshold}");

            let recovered = combine_secret(&all_shares[..threshold as usize]).unwrap();
            assert_eq!(
                recovered.as_slice(),
                secret,
                "first threshold shares of reversed n {shares_count}, t {threshold}"
            );
        }
    }

